SAMPLE_NAMES = [
    "Nouman", "Noman", "Nawaz", "Alex", "Sarah", "John", "David", "Leo", "Michael",
    "Emma", "Sophia", "Ali", "Ahmed", "Usman", "Hamza", "Zain", "Bilal", "Daniel",
    "Chris", "Emily", "Jessica", "James", "Robert", "William", "Lucas", "Oliver"
]

def generate_augmented_dataset(output_path, target_samples_per_intent=120):
    rows = []

    for intent, templates in INTENT_DATA.items():
        generated_for_intent = set()

        # 1. Base templates
        for tmpl in templates:
            if "{name}" in tmpl:
                for name in SAMPLE_NAMES:
                    phrase = tmpl.format(name=name).strip()
                    if phrase not in generated_for_intent:
                        generated_for_intent.add(phrase)
                        rows.append({"text": phrase, "intent": intent})
            else:
                phrase = tmpl.strip()
                if phrase not in generated_for_intent:
                    generated_for_intent.add(phrase)
                    rows.append({"text": phrase, "intent": intent})

        # 2. Augment with case variations, punctuation, and slight rephrasings
        base_list = list(generated_for_intent)
        while len(generated_for_intent) < target_samples_per_intent:
            base = random.choice(base_list)
            # Variations: lower, upper, add prefix/suffix
            variations = [
                base.lower(),
                base.capitalize(),
                f"Hey, {base.lower()}",
                f"Atlas, {base.lower()}",
                f"{base} please",
                f"Can you tell me, {base.lower()}",
                f"I want to know, {base.lower()}",
                f"{base}?",
                f"{base}!",
            ]
            cand = random.choice(variations).strip()
            if cand not in generated_for_intent:
                generated_for_intent.add(cand)
                rows.append({"text": cand, "intent": intent})

    df = pd.DataFrame(rows)
    # Shuffle dataset
    df = df.sample(frac=1.0, random_state=42).reset_index(drop=True)

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    df.to_csv(output_path, index=False)
    print(f"Generated augmented dataset: {output_path}")
    print(f"Total samples: {len(df)}")
    print(f"Total intents: {df['intent'].nunique()}")
    print("\nSamples per intent:")
    print(df['intent'].value_counts())
    return df

if __name__ == "__main__":
    out_csv = os.path.join(os.path.dirname(__file__), "chatbot_training_data.csv")
    generate_augmented_dataset(out_csv, target_samples_per_intent=130)
